// Writes the country seed for identity's Countries migration. Run once, when that migration was
// written; the output is committed and never regenerated for it (a migration must not change).
//
//   node tools/generate-countries.mjs > apps/identity/src/migrations/data/countries-2026-10.ts
//
// Codes and dial codes: libphonenumber-js (every region that has phone numbers). Names in en, ar
// and fr: the Unicode CLDR data in Node's Intl. Flags: the regional-indicator emoji.
import { getCountries, getCountryCallingCode } from 'libphonenumber-js';

/** The countries the app has offered so far, in their order, enabled for phone and origin. */
const ENABLED = ['AE', 'NG', 'GH', 'KE', 'ET', 'CM', 'SN', 'UG', 'ZA'];

const names = Object.fromEntries(
  ['en', 'ar', 'fr'].map((locale) => [locale, new Intl.DisplayNames([locale], { type: 'region' })]),
);
const flag = (code) =>
  String.fromCodePoint(...[...code].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));

const rows = getCountries()
  .map((code) => ({
    code,
    name: { en: names.en.of(code), ar: names.ar.of(code), fr: names.fr.of(code) },
    dialCode: `+${getCountryCallingCode(code)}`,
    flag: flag(code),
    enabled: ENABLED.includes(code),
    sortOrder: ENABLED.includes(code) ? ENABLED.indexOf(code) + 1 : 1000,
  }))
  .sort((a, b) => a.sortOrder - b.sortOrder || a.name.en.localeCompare(b.name.en, 'en'));

process.stdout.write(`/**
 * Every country with phone numbers, as seeded by the Countries migration (2026-10). Generated by
 * tools/generate-countries.mjs; do not edit. Later changes are made in the admin app, not here.
 */
export const COUNTRY_SEED: ReadonlyArray<{
  code: string;
  name: { en: string; ar: string; fr: string };
  dialCode: string;
  flag: string;
  enabled: boolean;
  sortOrder: number;
}> = ${JSON.stringify(rows, null, 2)};
`);
